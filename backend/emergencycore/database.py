"""SQLite for local use; psycopg PostgreSQL for Neon production."""
import re
import sqlite3
from contextlib import closing
from pathlib import Path
from flask import current_app, g

class Record(dict):
    def __getitem__(self, key):
        return list(self.values())[key] if isinstance(key, int) else super().__getitem__(key)

class Result:
    def __init__(self, cursor): self.cursor = cursor
    @property
    def rowcount(self): return self.cursor.rowcount
    def fetchone(self):
        row = self.cursor.fetchone()
        return Record(row) if row is not None else None
    def fetchall(self): return [Record(row) for row in self.cursor.fetchall()]
    def __iter__(self): return iter(self.fetchall())

class PostgresConnection:
    def __init__(self, url):
        import psycopg
        from psycopg.rows import dict_row
        self.raw = psycopg.connect(url, autocommit=True, row_factory=dict_row, connect_timeout=15, prepare_threshold=None)
        self.transactions = []
    def execute(self, sql, params=None):
        # Queries are application-owned. Leave quoted literals untouched and bind all values.
        parts = re.split(r"('(?:''|[^'])*')", sql)
        for index in range(0, len(parts), 2):
            parts[index] = re.sub(r'(?<!:):([A-Za-z_][A-Za-z0-9_]*)', r'%(\1)s', parts[index]).replace('?', '%s')
        return Result(self.raw.execute(''.join(parts), params))
    def __enter__(self):
        transaction = self.raw.transaction()
        transaction.__enter__()
        self.transactions.append(transaction)
        return self
    def __exit__(self, *args): return self.transactions.pop().__exit__(*args)
    def close(self): self.raw.close()

def connect(migrations=False):
    url = (current_app.config.get('DATABASE_URL_UNPOOLED') if migrations else None) or current_app.config.get('DATABASE_URL')
    if url:
        return PostgresConnection(url)
    conn = sqlite3.connect(current_app.config['DATABASE_PATH'], timeout=10)
    conn.row_factory = sqlite3.Row
    conn.execute('PRAGMA foreign_keys=ON')
    return conn

def get_db():
    if 'db' not in g: g.db = connect()
    return g.db

def run_schema(conn, sql):
    with conn:
        # Static DDL only; no user input or SQL function bodies.
        for statement in sql.split(';'):
            if statement.strip(): conn.execute(statement)

def init_database(app):
    postgres = bool(app.config.get('DATABASE_URL'))
    if not postgres: Path(app.config['DATABASE_PATH']).parent.mkdir(parents=True, exist_ok=True)
    with app.app_context(), closing(connect(migrations=True)) as conn:
        if not postgres: conn.execute('PRAGMA journal_mode=WAL')
        identity = 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' if postgres else 'INTEGER PRIMARY KEY AUTOINCREMENT'
        run_schema(conn, f"""CREATE TABLE IF NOT EXISTS incidents (
            id TEXT PRIMARY KEY, description TEXT NOT NULL, location TEXT NOT NULL,
            latitude DOUBLE PRECISION, longitude DOUBLE PRECISION, urgency TEXT NOT NULL,
            status TEXT NOT NULL, analysis TEXT NOT NULL, created_at TEXT NOT NULL, updated_at TEXT NOT NULL);
            CREATE TABLE IF NOT EXISTS events(id {identity}, type TEXT NOT NULL, payload TEXT NOT NULL, created_at TEXT NOT NULL);""")
    @app.teardown_appcontext
    def close_db(_error):
        if 'db' in g: g.pop('db').close()
